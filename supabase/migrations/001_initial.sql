-- Apply with the Supabase migration runner before starting the PostgreSQL backend.
-- The API uses a server-only database connection; browser clients use Auth + RLS.
begin;

create table public.users (
    id varchar(36) primary key,
    created_at varchar(40) not null
);
create table public.sessions (
    id varchar(36) primary key,
    owner_id varchar(36) not null references public.users(id) on delete cascade,
    question text not null,
    status varchar(20) not null check (status in ('queued','running','completed','incomplete','failed','cancelled')),
    request json not null,
    state json not null,
    error text,
    created_at varchar(40) not null,
    updated_at varchar(40) not null
);
create index ix_sessions_owner_created on public.sessions(owner_id, created_at);
create index ix_sessions_status on public.sessions(status);
create index ix_sessions_created_at on public.sessions(created_at);
create table public.plans (
    session_id varchar(36) primary key references public.sessions(id) on delete cascade,
    payload json not null
);
create table public.tasks (
    session_id varchar(36) not null references public.sessions(id) on delete cascade,
    id varchar(100) not null,
    question text not null,
    payload json not null,
    primary key(session_id, id)
);
create table public.sources (
    session_id varchar(36) not null references public.sessions(id) on delete cascade,
    id varchar(100) not null,
    title text not null,
    url text not null,
    source_type varchar(30) not null,
    payload json not null,
    primary key(session_id, id)
);
create index ix_sources_source_type on public.sources(source_type);
create table public.evidence (
    session_id varchar(36) not null references public.sessions(id) on delete cascade,
    id varchar(100) not null,
    source_id varchar(100) not null,
    text text not null,
    payload json not null,
    primary key(session_id, id),
    foreign key(session_id, source_id) references public.sources(session_id, id) on delete cascade
);
create index ix_evidence_source on public.evidence(session_id, source_id);
create table public.claims (
    session_id varchar(36) not null references public.sessions(id) on delete cascade,
    id varchar(100) not null,
    text text not null,
    status varchar(40) not null,
    payload json not null,
    primary key(session_id, id)
);
create index ix_claims_status on public.claims(status);
create table public.conflicts (
    session_id varchar(36) not null references public.sessions(id) on delete cascade,
    id varchar(100) not null,
    description text not null,
    resolved boolean not null default false,
    payload json not null,
    primary key(session_id, id)
);
create table public.gaps (
    session_id varchar(36) not null references public.sessions(id) on delete cascade,
    id varchar(100) not null,
    title text not null,
    category varchar(30) not null,
    payload json not null,
    primary key(session_id, id)
);
create table public.relationships (
    session_id varchar(36) not null references public.sessions(id) on delete cascade,
    id varchar(36) not null,
    relation varchar(40) not null,
    claim_id varchar(100),
    evidence_id varchar(100),
    source_id varchar(100),
    conflict_id varchar(100),
    gap_id varchar(100),
    primary key(session_id, id),
    foreign key(session_id, claim_id) references public.claims(session_id, id) on delete cascade,
    foreign key(session_id, evidence_id) references public.evidence(session_id, id) on delete cascade,
    foreign key(session_id, source_id) references public.sources(session_id, id) on delete cascade,
    foreign key(session_id, conflict_id) references public.conflicts(session_id, id) on delete cascade,
    foreign key(session_id, gap_id) references public.gaps(session_id, id) on delete cascade
);
create index ix_relationships_claim on public.relationships(session_id, claim_id);
create index ix_relationships_evidence on public.relationships(session_id, evidence_id);
create index ix_relationships_source on public.relationships(session_id, source_id);
create index ix_relationships_conflict on public.relationships(session_id, conflict_id);
create index ix_relationships_gap on public.relationships(session_id, gap_id);
create table public.events (
    id integer generated by default as identity primary key,
    session_id varchar(36) not null references public.sessions(id) on delete cascade,
    event_type varchar(100) not null,
    agent varchar(100) not null,
    message text not null,
    data json not null,
    timestamp varchar(40) not null
);
create index ix_events_session_cursor on public.events(session_id, id);
create table public.reports (
    session_id varchar(36) primary key references public.sessions(id) on delete cascade,
    title text not null,
    markdown text not null,
    payload json not null
);
create table public.followups (
    session_id varchar(36) not null references public.sessions(id) on delete cascade,
    id varchar(100) not null,
    question text not null,
    payload json not null,
    primary key(session_id, id)
);
create table public.documents (
    id varchar(36) primary key,
    owner_id varchar(36) not null references public.users(id) on delete cascade,
    title text not null,
    pages json not null,
    extraction_status varchar(30) not null,
    size_bytes integer not null,
    text_chars integer not null default 0,
    created_at varchar(40) not null
);
create index ix_documents_owner_id on public.documents(owner_id);
create table public.session_documents (
    session_id varchar(36) not null references public.sessions(id) on delete cascade,
    document_id varchar(36) not null references public.documents(id) on delete cascade,
    primary key(session_id, document_id)
);
create index ix_session_documents_document on public.session_documents(document_id);

alter table public.users enable row level security;
alter table public.users force row level security;
create policy users_owner on public.users for all to authenticated
    using (id = (select auth.uid())::text) with check (id = (select auth.uid())::text);
alter table public.sessions enable row level security;
alter table public.sessions force row level security;
create policy sessions_owner on public.sessions for all to authenticated
    using (owner_id = (select auth.uid())::text) with check (owner_id = (select auth.uid())::text);
alter table public.documents enable row level security;
alter table public.documents force row level security;
create policy documents_owner on public.documents for all to authenticated
    using (owner_id = (select auth.uid())::text) with check (owner_id = (select auth.uid())::text);

-- Every research child is authorized through its owning session, not a supplied owner field.
do $$
declare child text;
begin
    foreach child in array array['plans','tasks','sources','evidence','claims','relationships',
                                 'conflicts','gaps','events','reports','followups']
    loop
        execute format('alter table public.%I enable row level security', child);
        execute format('alter table public.%I force row level security', child);
        execute format(
            'create policy session_owner on public.%I for all to authenticated '
            'using (exists (select 1 from public.sessions s where s.id = session_id and s.owner_id = (select auth.uid())::text)) '
            'with check (exists (select 1 from public.sessions s where s.id = session_id and s.owner_id = (select auth.uid())::text))', child);
    end loop;
end $$;
alter table public.session_documents enable row level security;
alter table public.session_documents force row level security;
create policy session_documents_owner on public.session_documents for all to authenticated
    using (
        exists (select 1 from public.sessions s where s.id = session_id and s.owner_id = (select auth.uid())::text)
        and exists (select 1 from public.documents d where d.id = document_id and d.owner_id = (select auth.uid())::text)
    ) with check (
        exists (select 1 from public.sessions s where s.id = session_id and s.owner_id = (select auth.uid())::text)
        and exists (select 1 from public.documents d where d.id = document_id and d.owner_id = (select auth.uid())::text)
    );

revoke all on public.users, public.sessions, public.plans, public.tasks, public.sources,
    public.evidence, public.claims, public.relationships, public.conflicts, public.gaps,
    public.events, public.reports, public.followups, public.documents, public.session_documents from anon, public;
-- The browser uses Supabase Auth only. Application tables are API-only so a
-- valid browser token cannot bypass FastAPI validation, quotas, or workflow
-- state transitions through the Supabase REST endpoint. The server's
-- DATABASE_URL role is responsible for application DML.
revoke all on public.users, public.sessions, public.plans, public.tasks, public.sources,
    public.evidence, public.claims, public.relationships, public.conflicts, public.gaps,
    public.events, public.reports, public.followups, public.documents, public.session_documents from authenticated;
grant select, insert, update, delete on public.users, public.sessions, public.plans, public.tasks,
    public.sources, public.evidence, public.claims, public.relationships, public.conflicts,
    public.gaps, public.events, public.reports, public.followups, public.documents,
    public.session_documents to service_role;
grant usage, select on sequence public.events_id_seq to service_role;

commit;
